-- PUN generico del mese
CREATE TABLE pun (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mese integer NOT NULL,
    anno integer NOT NULL,
    f1 Double precision NOT NULL,
    f2 Double precision NOT NULL,
    f3 Double precision NOT NULL,
    CONSTRAINT uk_pun_mese_anno UNIQUE (mese, anno)
);

-- PUN specifico di un POD nel mese: se presente prevale su quello generico
CREATE TABLE pun_pod (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mese integer NOT NULL,
    anno integer NOT NULL,
    f1 Double precision NOT NULL,
    f2 Double precision NOT NULL,
    f3 Double precision NOT NULL,
    fornitura_pod character varying(255) NOT NULL,
    CONSTRAINT uk_pun_pod_fornitura_mese_anno UNIQUE (fornitura_pod, mese, anno)
);

-- importi da addebitare su una fornitura in un mese (es. morosita', pratiche); se esente_iva l'importo e' fuori
-- dall'imponibile (gia' comprensivo di iva o fuori campo), altrimenti e' imponibile e paga l'iva della fornitura
CREATE TABLE altre_partite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fornitura_pod character varying(255) NOT NULL,
    voce character varying(255) NOT NULL,
    importo Double precision NOT NULL,
    esente_iva boolean NOT NULL DEFAULT true,
    mese integer NOT NULL,
    anno integer NOT NULL
);

-- fatture del fornitore all'ingrosso verso IEG, importate dai csv di riepilogo (una riga per voce per POD)
CREATE TABLE fatture_fornitore (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero character varying(255) NOT NULL,
    data_emissione date,
    data_scadenza date,
    nome_file character varying(255),
    data_import timestamp NOT NULL,
    righe integer NOT NULL,
    totale_imponibile Double precision NOT NULL,
    CONSTRAINT uk_fatture_fornitore_numero UNIQUE (numero)
);

