CREATE SEQUENCE letture_id_seq
    START WITH 1
    INCREMENT BY 1
    CACHE 20;

CREATE TABLE letture (
    id BIGINT NOT NULL DEFAULT nextval('letture_id_seq') PRIMARY KEY,
    fornitura_pod character varying(255) NOT NULL,
    data_lettura date NOT NULL,
    is_utile boolean,
    validato character varying(255),
    tipo_dato character varying(255),
    tipo_lettura character varying(255) NOT NULL,
    causa_ostativa character varying(255),
    tipo_contatore character varying(255) NOT NULL,
    raccolta character varying(255),
    ea_f1 Double precision NOT NULL,
    ea_f2 Double precision NOT NULL,
    ea_f3 Double precision NOT NULL,
    er_f1 Double precision,
    er_f2 Double precision,
    er_f3 Double precision,
    pot_f1 Double precision,
    pot_f2 Double precision,
    pot_f3 Double precision,
    ka Double precision,
    kr Double precision,
    kp Double precision,
    pot_max character varying(255),
    note character varying(255)
);

