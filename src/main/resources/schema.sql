CREATE TABLE clienti (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ragione_sociale character varying(255) NOT NULL,
    active boolean,
    piva character varying(255),
    cf character varying(255),
    indirizzo character varying(255),
    civico character varying(255),
    cap integer,
    comune character varying(255),
    provincia character varying(255),
    telefono character varying(255),
    email character varying(255)
);

CREATE TABLE dispacciamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    costo_am Double precision NOT NULL,
    dis Double precision NOT NULL,
    capacita Double precision NOT NULL,
    sbilanciamento Double precision NOT NULL,
    mese integer NOT NULL,
    anno integer NOT NULL
);

