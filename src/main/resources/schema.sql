    pod character varying(255) NOT NULL PRIMARY KEY,
    cliente_id bigint NOT NULL,
    active boolean,
    indirizzo character varying(255),
    civico character varying(255),
    cap integer,
    comune character varying(255),
    provincia character varying(255),
    bta character varying(255) NOT NULL,
    potenza_disponibile Double precision NOT NULL,
    potenza_impegnata Double precision NOT NULL,
    tipo_prelievo character varying(255) NOT NULL,
    tipo_contatore character varying(255) NOT NULL,
    codice_distributore character varying(255) NOT NULL,
    fornitore character varying(255),
    fatturazione character varying(255) NOT NULL,
    iva Double precision NOT NULL,
