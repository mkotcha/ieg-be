    chiave character varying(255) NOT NULL,
    perdite boolean NOT NULL DEFAULT false,
    voce_confronto character varying(255) NOT NULL,
    quantita boolean NOT NULL DEFAULT false,
    CONSTRAINT uk_mappature_voci_fornitore UNIQUE (chiave, perdite)
);

