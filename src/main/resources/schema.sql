    quantita Double precision,
    unitario Double precision,
    perc_iva Double precision,
    importo Double precision NOT NULL,
    descrizione character varying(255),
    cod_offerta character varying(255),
    cod_tariffa character varying(255),
    nr_articolo character varying(255),
    tipo_ricalcolo character varying(255),
    motivo_ricalcolo character varying(255),
    tipo_mercato character varying(255),
    potenza_impegnata Double precision,
    potenza_disponibile Double precision,
